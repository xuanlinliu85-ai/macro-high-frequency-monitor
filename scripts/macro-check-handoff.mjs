/** Validate the compact AI handoff contract and canonical snapshot lineage. */
import { resolve } from "node:path";
import { gitInfo, parseArgs, readJson, ROOT, sha256File, stableJson } from "./macro-automation-lib.mjs";
const args = parseArgs();
const handoffPath = resolve(ROOT, String(args.input || "dist/ai-handoff-latest.json"));
const snapshotPath = resolve(ROOT, String(args.snapshot || "public/macro-snapshot.json"));
const handoff = readJson(handoffPath), snapshot = readJson(snapshotPath), current = gitInfo();
const checks = [], forbiddenKeys = [], credentialKeys = [], secretValues = [];
const check = (name, pass, detail) => checks.push({ name, pass: Boolean(pass), detail });
const walk = (value, path = "$") => {
  const key = path.split(".").at(-1).replace(/\[\d+\]$/g, "");
  if (/^(?:history|observations|points|rawSeries|series|trends)$/i.test(key)) forbiddenKeys.push(path);
  if (/(?:api[_-]?key|authorization|cookie|credential|access[_-]?token|secret)$/i.test(key)) credentialKeys.push(path);
  if (typeof value === "string" && /(?:Bearer\s+[A-Za-z0-9._~-]{8,}|[?&](?:api_key|token|access_token|key)=[^&\s]+)/i.test(value)) secretValues.push(path);
  if (Array.isArray(value)) value.forEach((child, index) => walk(child, `${path}[${index}]`));
  else if (value && typeof value === "object") Object.entries(value).forEach(([childKey, child]) => walk(child, `${path}.${childKey}`));
};
walk(handoff);
check("contract", handoff.contract === "AI_MACRO_HANDOFF", `${handoff.contract}`);
check("version", handoff.version === "1.0.0", `${handoff.version}`);
check("snapshot contract", handoff.source?.contract === "MACRO_SNAPSHOT", `${handoff.source?.contract}`);
check("snapshot version", handoff.source?.version === "1.1.0", `${handoff.source?.version}`);
check("asOf", Boolean(handoff.asOf) && handoff.asOf === snapshot.asOf, `${handoff.asOf}`);
check("generatedAt", Boolean(handoff.generatedAt), `${handoff.generatedAt}`);
check("snapshot sha256", handoff.source?.sha256 === sha256File(snapshotPath), "source file digest");
check("source commit", handoff.source?.sourceCommit === current.sourceCommit, current.sourceCommit);
check("source clean", handoff.source?.sourceDirty === false && current.sourceDirty === false, `handoff=${handoff.source?.sourceDirty} current=${current.sourceDirty}`);
check("six dimensions", Array.isArray(handoff.dimensions) && handoff.dimensions.length === 6, `${handoff.dimensions?.length || 0}`);
check("headline", Boolean(handoff.headline && Number.isFinite(handoff.headline.composite)), "composite present");
check("freshness", Boolean(handoff.freshness && typeof handoff.freshness === "object"), "present");
check("summary blocks", ["deviations", "anomalies", "divergences", "aggregates", "meta"].every(key => handoff[key] != null), "all present");
check("futures current state", Array.isArray(handoff.futures?.varieties) && Array.isArray(handoff.futures?.spreads), `${handoff.futures?.varieties?.length || 0} varieties`);
check("graph lineage", stableJson(handoff.futures?.graph?.edges || []) === stableJson(snapshot.futures?.graph?.edges || []), `${handoff.futures?.graph?.edges?.length || 0} edges`);
check("raw series excluded", forbiddenKeys.length === 0, forbiddenKeys.slice(0, 3).join(", ") || "none");
check("secret scan", secretValues.length === 0, secretValues.slice(0, 3).join(", ") || "none");
check("credential keys excluded", credentialKeys.length === 0, credentialKeys.slice(0, 3).join(", ") || "none");
for (const item of checks) console.log(`${item.pass ? "PASS" : "FAIL"} ${item.name}: ${item.detail}`);
console.log(`结果：${checks.filter(item => item.pass).length}/${checks.length} 通过`);
if (checks.some(item => !item.pass)) process.exitCode = 1;
